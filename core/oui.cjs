/** Normalize a MAC address to AA:BB:CC:DD:EE:FF form, or null if invalid. */
function normalizeMac(mac) {
  if (!mac) return null;
  const hex = String(mac).replace(/[^0-9a-fA-F]/g, "").toUpperCase();
  if (hex.length !== 12) return null;
  return (hex.match(/.{2}/g) || []).join(":");
}

/** Look up the vendor for a MAC address. Returns null when unknown. */
function lookupVendor(mac) {
  const normalized = normalizeMac(mac);
  if (!normalized) return null;
  const prefix = normalized.replace(/:/g, "").slice(0, 6);
  if (OUI[prefix]) return OUI[prefix];

  // Locally administered addresses (second-least-significant bit of first
  // octet set) are randomized - common on modern phones.
  const firstOctet = parseInt(normalized.slice(0, 2), 16);
  if (Number.isFinite(firstOctet) && (firstOctet & 0x02) !== 0) {
    return "Randomized (private) MAC";
  }
  return null;
}

module.exports = { lookupVendor, normalizeMac, OUI };
